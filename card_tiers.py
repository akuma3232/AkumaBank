DEFAULT_TIER = "standard"


def get_card_tier(tier_id: str) -> dict:
    """Retrieve card tier specification by ID, falling back to default."""
    if not tier_id:
        return CARD_TIERS[DEFAULT_TIER]
    # Handle old legacy IDs if encountered
    legacy_mapping = {
        "classic-blue": "standard",
        "student-cyber": "student",
        "women-elegance": "women",
        "royal-gold": "gold",
        "titanium-business": "business",
        "sapphire-travel": "travel",
        "green-eco": "eco",
        "gaming-neon": "student",
        "freelancer-pro": "freelance",
        "vault-infinity": "infinite",
        "vip-obsidian": "infinite",
    }
    normalized_id = legacy_mapping.get(tier_id, tier_id)
    return CARD_TIERS.get(normalized_id) or CARD_TIERS[DEFAULT_TIER]


def list_card_tiers() -> list:
    """Return all card tiers as a list."""
    return list(CARD_TIERS.values())
